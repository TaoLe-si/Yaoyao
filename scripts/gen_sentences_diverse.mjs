// 多样化「原样复制」句子生成器。
//
// 动因（doc 28 §二）：L6 语料的原样复制只有 **15 个唯一句 × 40 次重复**，
// 模型学到的是查表而非复制回路：语料内 6/6、语料外 0/5，
// 且语料外时吐出的是**语料内另一句**（`妈妈在做饭。`）或复读。
//
// 目标：唯一句数 ≥ 样本数的 50%，句式/长度/主题充分铺开，
// 使"复制"成为比"记忆"更省力的解。
//
// 用法: node scripts/gen_sentences_diverse.mjs <数量> [seed]
import fs from 'node:fs';

const N = parseInt(process.argv[2] || '3000', 10);
const SEED = parseInt(process.argv[3] || '20260922', 10);

let seed = SEED;
const rnd = () => { seed = (seed * 1103515245 + 12345) & 0x7fffffff; return seed / 0x7fffffff; };
const pick = (a) => a[Math.floor(rnd() * a.length)];

// ---- 词库：刻意扩大，确保组合空间远超需要的句数 ----
const PERSON = ['弟弟','妹妹','哥哥','姐姐','爷爷','奶奶','爸爸','妈妈','叔叔','阿姨','小张','小王','小李','小明','小红','小刚','小丽','老师','同学','医生','护士','司机','工人','农民','学生','孩子','老人','邻居','表哥','表妹','舅舅','姑姑','诗人','画家','歌手','球员','教练','警察','消防员'];
const ANIMAL = ['小猫','小狗','兔子','小鸟','金鱼','乌龟','熊猫','大象','猴子','老虎','狮子','蝴蝶','蜜蜂','松鼠','鸭子','公鸡','山羊','白马','绵羊','青蛙'];
const THING  = ['苹果','桃子','草莓','西瓜','葡萄','香蕉','橙子','书','铅笔','橡皮','书包','桌子','椅子','台灯','水杯','雨伞','地图','钟表','尺子','帽子','外套','鞋子','眼镜','手机','电脑','电视','自行车','汽车','火车','飞机','轮船','花瓶','窗帘','地毯','枕头','被子','碗','盘子','筷子','勺子'];
const PLACE  = ['公园','学校','医院','图书馆','超市','车站','操场','教室','厨房','阳台','花园','山顶','河边','海边','田野','森林','街道','广场','博物馆','电影院','动物园','菜市场','办公室','实验室','体育馆'];
const TIME   = ['早上','中午','下午','晚上','今天','明天','昨天','周末','春天','夏天','秋天','冬天','清晨','傍晚','半夜','星期天'];
const ADV    = ['认真','仔细','安静','开心','慢慢地','飞快地','悄悄地','高兴地','努力','一起','已经','正在','刚刚','常常','偶尔'];
const NUM    = ['一','两','三','四','五','六','七','八','九','十','7','12','20','35','100','3'];
const OBJ_CNT= ['个','只','本','张','把','条','件','块','杯','朵'];

// ---- 句型模板 ----
const TPL = [
  () => `${pick(PERSON)}在${pick(['写字','看书','画画','唱歌','跳舞','跑步','做饭','下棋','喝茶','散步','睡觉','买菜','打球','备课','洗碗','浇花','写信','听音乐','看电视','整理房间'])}。`,
  () => `${pick(PERSON)}和${pick(PERSON)}一起去了${pick(PLACE)}。`,
  () => `${pick(TIME)}，${pick(PERSON)}在${pick(PLACE)}${pick(['看书','散步','打球','画画','聊天','休息','等人','拍照'])}。`,
  () => `${pick(ANIMAL)}在${pick(['吃草','睡觉','玩耍','叫个不停','追蝴蝶','晒太阳','找食物','游泳'])}。`,
  () => `${pick(PLACE)}里有很多${pick(THING)}。`,
  () => `${pick(PERSON)}${pick(ADV)}地${pick(['走过去','坐下来','拿起书','打开门','关上窗','抬起头','笑了笑','点了点头'])}。`,
  () => `桌子上有${pick(NUM)}${pick(OBJ_CNT)}${pick(THING)}。`,
  () => `我${pick(['喜欢','讨厌','想要','买了一个','看见了','找到了','弄丢了'])}${pick(THING)}。`,
  () => `${pick(THING)}和${pick(THING)}都很好。`,
  () => `${pick(PERSON)}说：“${pick(['今天天气不错','我们出发吧','这件事很重要','请你帮个忙','明天见','我明白了'])}。”`,
  () => `${pick(PLACE)}的${pick(['风景','空气','声音','味道','气氛'])}非常${pick(['好','安静','热闹','特别','舒服'])}。`,
  () => `${pick(TIME)}的${pick(['阳光','风','雨','雪','云'])}${pick(['很大','很小','很温柔','停了','来了'])}。`,
  () => `${pick(PERSON)}把${pick(THING)}放在了${pick(['桌上','椅子上','窗台上','门口','包里','书架上','地上'])}。`,
  () => `${pick(ANIMAL)}和${pick(ANIMAL)}是${pick(['好朋友','邻居','兄弟','对手'])}。`,
  () => `${pick(PERSON)}${pick(['今年','上个月','昨天','下周'])}要去${pick(PLACE)}。`,
  () => `这${pick(OBJ_CNT)}${pick(THING)}是${pick(PERSON)}的。`,
  () => `${pick(NUM)}${pick(OBJ_CNT)}${pick(THING)}一共${pick(['很便宜','很贵','很重','很轻','很漂亮'])}。`,
  () => `${pick(PERSON)}一边${pick(['走','听','吃','看'])}一边${pick(['说话','笑','想事情','点头'])}。`,
  () => `如果${pick(['下雨','天晴','有空','不忙'])}，我们就去${pick(PLACE)}。`,
  () => `${pick(PERSON)}觉得${pick(THING)}${pick(['很好看','很好吃','很实用','太重了','太小了'])}。`,
];

const seen = new Set();
const out = [];
let guard = 0;
while (out.length < N && guard < N * 400) {
  guard++;
  const s = TPL[Math.floor(rnd() * TPL.length)]();
  if (seen.has(s)) continue;
  if (s.length < 4 || s.length > 40) continue;
  seen.add(s); out.push(s);
}

fs.mkdirSync('D:/TaoVm/data/verbatim_diverse', { recursive: true });
fs.writeFileSync('D:/TaoVm/data/verbatim_diverse/sentences.txt', out.join('\n') + '\n', 'utf8');
console.log(`生成 ${out.length} 个唯一句（尝试 ${guard} 次，唯一率 ${(100 * out.length / (guard || 1)).toFixed(1)}%）`);
const lens = {};
for (const s of out) { const k = s.length; lens[k] = (lens[k] || 0) + 1; }
console.log('长度分布(字): ' + Object.keys(lens).sort((a, b) => a - b).map(k => `${k}:${lens[k]}`).join(' '));
console.log('样例: ' + out.slice(0, 8).join(' / '));
