// ── H. 话题承接（400）─────────────────────────────────────────────
const TOPICS = [['我想学弹钢琴。','需要买什么？','一架钢琴。'],['我想学书法。','先练什么？','先练基本笔画。'],['我想学游泳。','要注意什么？','注意安全。'],['我想学做饭。','先学什么？','先学煮饭。'],['我想学画画。','买什么工具？','铅笔和画纸。']];
