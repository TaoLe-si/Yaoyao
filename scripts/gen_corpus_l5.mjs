// L5 语料生成器：针对 doc 16 修正后的真实缺陷——「两问合一时模型答完第一槽位就结束回合」。
//
// L4 的证据：
//   单问「我叫什么名字？」 -> 名字 9/12
//   单问「我喜欢什么？」   -> 颜色 12/12
//   两问合一「我叫什么名字？喜欢什么？」 -> 名字 9/12、颜色 0/12（答完名字即 end=259）
//   L4 中该问法有 1728 条且答案格式正确（X，Y。），故不是数据缺失。
//
// L5 的改动（其余与 L4 同分布，便于对照）：
//   1. 多问合一的样本量 1728 -> 7200，且用 6 种问法（防止前缀匹配）
//   2. 单问形式的样本量下调（2500 -> 1600），降低其对「答完第一槽位就停」的先验
//   3. 新增「先问一半、再补问另一半」的负样本（让模型学会区分一问与两问）
//   4. held-out 名字集与 L4 相同，继续排除在训练之外
//
// 用法: node scripts/gen_corpus_l5.mjs <输出目录>
import fs from 'node:fs';

const OUT = process.argv[2] || 'D:/TaoVm/data/noffn_l5';

const SUR = '赵钱孙李周吴郑王冯陈褚卫蒋沈韩杨朱秦尤许何吕施张孔曹严华金魏陶姜戚谢邹喻柏水窦章云苏潘葛奚范彭郎鲁韦昌马苗凤花方俞任袁柳鲍史唐费廉岑薛雷贺倪汤滕殷罗毕郝邬安常乐于时傅皮齐康伍余元卜顾孟平黄和穆萧尹湛汪祁毛禹狄米贝明臧计伏成戴谈宋茅庞熊纪舒屈项祝董梁杜阮蓝闵席季麻强贾路娄危江童颜郭林徐高夏蔡田樊胡凌霍虞万支柯昝管卢莫';
const GIV = ['伟','芳','娜','秀英','敏','静','丽','强','磊','洋','艳','勇','军','杰','娟','涛','明','超','秀兰','霞','平','刚','桂英','建国','文','辉','华','慧','燕','鹏','飞','宇','浩','晨','雪','琳','佳','婷','悦','辰','鑫','博','凯','宁','欣','怡','然','嘉','梦','雅','子涵','雨泽','梓萱','思远','若曦','明轩','子墨','一诺','浩然','诗涵','俊杰','晓东','志强','国华','春花','秋月','冬梅','小刚','小明','小红','小军','小丽','小华','小燕','小峰','小云','小龙','小凤','小鹏','小虎'];
const LIKES = ['红色','蓝色','绿色','黄色','紫色','白色','粉色','青色','橙色','棕色','灰色','金色','银色','黑色','米色','跑步','看书','游泳','画画','唱歌','下棋','钓鱼','篮球','足球','排球','羽毛球','乒乓球','爬山','骑车','跳舞','弹琴','写字','做饭','种花','养鱼','喝茶','喝咖啡','看电影','听音乐','拍照','旅行','猫','狗','鱼','鸟','兔子','仓鼠','乌龟','马','牛','羊','鸡','鸭','苹果','香蕉','橙子','葡萄','西瓜','草莓','桃子','梨','橘子','芒果','荔枝','樱桃','米饭','面条','饺子','包子','馒头','面包','蛋糕','巧克力','牛奶','豆浆','茶','咖啡','果汁'];
const ITEMS = ['红色','黄色','蓝色','粉色','橙色','紫色','绿色','白色','猫','狗','鱼','鸡','兔子','马','苹果','香蕉','橙子','葡萄','西瓜','草莓','桃子','桌子','椅子','书包','尺子','橡皮','地图','钟表','水杯','雨伞','铅笔','笔记本','北京','上海','杭州','成都','广州','南京','武汉','西安','重庆','天津'];
// 与 L4 相同的 sealed 名字，绝不入训
const SEALED = new Set(['马超','郭静','孙丽','小林','小马','小孙','刘洋','小树','邬晓东','鲁刚','毛小华','魏娜','梁华','罗明轩','孔桂英','谢小虎','任小凤','柏小军','夏勇','高然']);

let seed = 20260914;
const rnd = () => { seed = (seed * 1103515245 + 12345) & 0x7fffffff; return seed / 0x7fffffff; };
const pick = a => a[Math.floor(rnd() * a.length)];
function name() {
  for (let i = 0; i < 60; i++) {
    const n = pick(SUR.split('')) + pick(GIV);
    if (!SEALED.has(n)) return n;
  }
  return '阿' + pick(GIV);
}

const docs = [];
const add = t => docs.push(t);

// ── A. 多问合一（7200）：核心修复目标 ─────────────────────────────
// 6 种问法 × 1200。答案一律「名字，喜好。」（与 L4 一致）
const COMBINED = [
  q => `我叫什么名字？喜欢什么？`,
  q => `我叫什么名字？我喜欢什么？`,
  q => `我叫什么？喜欢什么？`,
  q => `我叫什么名字，喜欢什么？`,
  q => `请说出我的名字和喜好。`,
  q => `我的名字和喜好分别是什么？`,
];
for (let i = 0; i < 7200; i++) {
  const n = name(), a = pick(LIKES);
  const form = COMBINED[i % COMBINED.length];
  const k = i % 3;
  if (k === 0) add([['U', `我的名字叫${n}，我喜欢${a}。请记住。`], ['A', `记住了，你叫${n}，喜欢${a}。`], ['U', form()], ['A', `${n}，${a}。`]]);
  else if (k === 1) add([['U', `请记住：我叫${n}，最喜欢${a}。`], ['A', '记住了。'], ['U', form()], ['A', `${n}，${a}。`]]);
  else add([['U', `我叫${n}，喜欢${a}，请记住。`], ['A', '好的，我记住了。'], ['U', form()], ['A', `${n}，${a}。`]]);
}

// ── B. 单问（1600）：保留能力，但降低「答完第一槽位就停」的先验 ──
for (let i = 0; i < 1600; i++) {
  const n = name(), a = pick(LIKES);
  if (i % 2) add([['U', `我的名字叫${n}，我喜欢${a}。请记住。`], ['A', '记住了。'], ['U', '我叫什么名字？'], ['A', `${n}。`]]);
  else add([['U', `我的名字叫${n}，我喜欢${a}。请记住。`], ['A', '记住了。'], ['U', '我喜欢什么？'], ['A', `${a}。`]]);
}

// ── C. 一问一答交替（1200）：明确「只问一半就只答一半」的边界 ────
for (let i = 0; i < 1200; i++) {
  const n = name(), a = pick(LIKES);
  add([['U', `我的名字叫${n}，我喜欢${a}。请记住。`], ['A', '记住了。'], ['U', '我叫什么名字？'], ['A', `${n}。`], ['U', '喜欢什么？'], ['A', `${a}。`]]);
}

// ── D. 列表复制（3000）────────────────────────────────────────────
for (let i = 0; i < 3000; i++) {
  const k = 2 + (i % 5), seq = [];
  for (let j = 0; j < k; j++) seq.push(pick(ITEMS));
  const s = seq.join('、');
  if (i % 3 === 0) add([['U', `按顺序复述：${s}。`], ['A', s]]);
  else if (i % 3 === 1) add([['U', `请按顺序输出：${s}。不要添加其他文字。`], ['A', s]]);
  else add([['U', `请依次说出：${s}。`], ['A', s]]);
}

// ── E. 原样复制（1200）────────────────────────────────────────────
const SENTS = ['小王在看书。','我住在上海。','桌子上有7个苹果。','草莓和桃子都很好。','今天天气很好。','他在跑步。','我喜欢喝茶。','河里有三条鱼。','学校在山脚下。','晚上八点睡觉。','妈妈在做饭。','弟弟在写字。','外面下雨了。','老师进来了。','我们一起去公园。'];
for (let i = 0; i < 1200; i++) {
  const s = pick(SENTS);
  if (i % 2) add([['U', `请重复这句话：${s}`], ['A', s]]);
  else add([['U', `原样输出：${s}`], ['A', s]]);
}

// ── F. 算术（2000）────────────────────────────────────────────────
for (let i = 0; i < 2000; i++) {
  const a = 1 + Math.floor(rnd() * 20), b = 1 + Math.floor(rnd() * 20);
  if (i % 3 === 0) add([['U', `${a}+${b}等于多少？`], ['A', String(a + b)]]);
  else if (i % 3 === 1) add([['U', `只输出数字：${a}×${b}等于多少？`], ['A', String(a * b)]]);
  else add([['U', `小明有${a}个苹果，又买了${b}个，一共有几个苹果？`], ['A', String(a + b)]]);
}

