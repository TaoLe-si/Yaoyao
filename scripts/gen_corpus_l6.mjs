// L6 语料生成器：修 L5 残留的「两问合一答完第一槽位就停」。
//
// L5 的实测（H2R_L5 step_400，12 个 held-out 名字，问「我叫什么名字？喜欢什么？」）：
//   正确产出「X，Y。」     3/12
//   只产出「X。」后结束   7/12
//   退化重复到 64 token   2/12
//
// 根因（不是记忆容量，L5 已证明两个槽位都能读出）：
//   「我叫什么名字？」是「我叫什么名字？喜欢什么？」的**前缀**，而两者的
//   **答案首 token 相同**（都从名字 X 开始）。语料里单问样本更多，
//   于是「X。」的先验压过「X，Y。」。
//
// L6 的修法：
//   1. **合一问法的答案首 token 改为「你叫」** → 「你叫X，喜欢Y。」
//      与单问的「X。」首 token 完全不同，前缀歧义彻底消除。
//   2. 单问样本再降（名字 800 / 喜好 800），合一升到 9600（6 种问法 × 1600）。
//   3. 新增「两个槽位都问但顺序相反」的问法，强化「按问的数量作答」。
//   4. held-out 名字集不变，继续排除。
//
// 用法: node scripts/gen_corpus_l6.mjs <输出目录>
