let seed = 20260915;
const rnd = () => { seed = (seed * 1103515245 + 12345) & 0x7fffffff; return seed / 0x7fffffff; };
const pick = a => a[Math.floor(rnd() * a.length)];
function name() {
  for (let i = 0; i < 60; i++) { const n = pick(SUR.split('')) + pick(GIV); if (!SEALED.has(n)) return n; }
  return '阿' + pick(GIV);
}

const docs = [];
const add = t => docs.push(t);

// ── A. 两问合一（9600）：答案首 token = 「你叫」，与单问彻底区分 ──
const COMBINED = [
  ['我叫什么名字？喜欢什么？',       (n, a) => `你叫${n}，喜欢${a}。`],
  ['我叫什么名字？我喜欢什么？',     (n, a) => `你叫${n}，喜欢${a}。`],
  ['我叫什么？喜欢什么？',           (n, a) => `你叫${n}，喜欢${a}。`],
  ['请说出我的名字和喜好。',         (n, a) => `你叫${n}，喜欢${a}。`],
  ['我的名字和喜好分别是什么？',     (n, a) => `你叫${n}，喜欢${a}。`],
  ['喜欢什么？我叫什么名字？',       (n, a) => `你喜欢${a}，你叫${n}。`],  // 顺序相反
];
for (let i = 0; i < 9600; i++) {
  const n = name(), a = pick(LIKES);
  const [q, fmt] = COMBINED[i % COMBINED.length];
  const k = i % 3;
  if (k === 0) add([['U', `我的名字叫${n}，我喜欢${a}。请记住。`], ['A', `记住了，你叫${n}，喜欢${a}。`], ['U', q], ['A', fmt(n, a)]]);
  else if (k === 1) add([['U', `请记住：我叫${n}，最喜欢${a}。`], ['A', '记住了。'], ['U', q], ['A', fmt(n, a)]]);
  else add([['U', `我叫${n}，喜欢${a}，请记住。`], ['A', '好的，我记住了。'], ['U', q], ['A', fmt(n, a)]]);
}

// ── B. 单问（各 800）：答案仍是「X。」/「Y。」，首 token 与合一不同 ──
for (let i = 0; i < 800; i++) {
  const n = name(), a = pick(LIKES);
  add([['U', `我的名字叫${n}，我喜欢${a}。请记住。`], ['A', '记住了。'], ['U', '我叫什么名字？'], ['A', `${n}。`]]);
}
for (let i = 0; i < 800; i++) {
  const n = name(), a = pick(LIKES);
  add([['U', `我的名字叫${n}，我喜欢${a}。请记住。`], ['A', '记住了。'], ['U', '我喜欢什么？'], ['A', `${a}。`]]);
}

// ── C. 一问一答交替（1000）：教「只问一半就只答一半」 ──
for (let i = 0; i < 1000; i++) {
  const n = name(), a = pick(LIKES);
  add([['U', `我的名字叫${n}，我喜欢${a}。请记住。`], ['A', '记住了。'], ['U', '我叫什么名字？'], ['A', `${n}。`], ['U', '喜欢什么？'], ['A', `${a}。`]]);
}

// ── D. 列表复制（3000）──
for (let i = 0; i < 3000; i++) {
  const k = 2 + (i % 5), seq = [];
  for (let j = 0; j < k; j++) seq.push(pick(ITEMS));
  const s = seq.join('、');
  if (i % 3 === 0) add([['U', `按顺序复述：${s}。`], ['A', s]]);
  else if (i % 3 === 1) add([['U', `请按顺序输出：${s}。不要添加其他文字。`], ['A', s]]);
  else add([['U', `请依次说出：${s}。`], ['A', s]]);
}

// ── E. 原样复制（1200）──
