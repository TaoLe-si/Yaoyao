const GIV = ['伟','芳','娜','秀英','敏','静','丽','强','磊','洋','艳','勇','军','杰','娟','涛','明','超','秀兰','霞','平','刚','桂英','建国','文','辉','华','慧','燕','鹏','飞','宇','浩','晨','雪','琳','佳','婷','悦','辰','鑫','博','凯','宁','欣','怡','然','嘉','梦','雅','子涵','雨泽','梓萱','思远','若曦','明轩','子墨','一诺','浩然','诗涵','俊杰','晓东','志强','国华','春花','秋月','冬梅','小刚','小明','小红','小军','小丽','小华','小燕','小峰','小云','小龙','小凤','小鹏','小虎'];
const LIKES = ['红色','蓝色','绿色','黄色','紫色','白色','粉色','青色','橙色','棕色','灰色','金色','银色','黑色','米色','跑步','看书','游泳','画画','唱歌','下棋','钓鱼','篮球','足球','排球','羽毛球','乒乓球','爬山','骑车','跳舞','弹琴','写字','做饭','种花','养鱼','喝茶','喝咖啡','看电影','听音乐','拍照','旅行','猫','狗','鱼','鸟','兔子','仓鼠','乌龟','马','牛','羊','鸡','鸭','苹果','香蕉','橙子','葡萄','西瓜','草莓','桃子','梨','橘子','芒果','荔枝','樱桃','米饭','面条','饺子','包子','馒头','面包','蛋糕','巧克力','牛奶','豆浆','茶','咖啡','果汁'];
const ITEMS = ['红色','黄色','蓝色','粉色','橙色','紫色','绿色','白色','猫','狗','鱼','鸡','兔子','马','苹果','香蕉','橙子','葡萄','西瓜','草莓','桃子','桌子','椅子','书包','尺子','橡皮','地图','钟表','水杯','雨伞','铅笔','笔记本','北京','上海','杭州','成都','广州','南京','武汉','西安','重庆','天津'];
